const fs = require('fs');
const path = require('path');

// Read raw API URL from supported environment variable names
const rawUrl = (
  process.env.API_URL ||
  process.env.VITE_API_URL ||
  process.env.NG_APP_API_URL ||
  process.env.BACKEND_URL ||
  ''
).trim();

// Format URL or fallback to default
let apiUrl = 'http://127.0.0.1:8000/api/v1';

if (!rawUrl) {
  console.warn('[set-env] WARNING: No API_URL, VITE_API_URL, or BACKEND_URL provided! Falling back to localhost "http://127.0.0.1:8000/api/v1". Ensure API_URL is configured in your production CI/CD environment.');
}

if (rawUrl) {
  // Strip trailing slashes
  let formattedUrl = rawUrl.replace(/\/+$/, '');

  // Append /api/v1 if not already present
  if (!formattedUrl.endsWith('/api/v1')) {
    // If it ends with /api, just append /v1
    if (formattedUrl.endsWith('/api')) {
      formattedUrl = `${formattedUrl}/v1`;
    } else {
      formattedUrl = `${formattedUrl}/api/v1`;
    }
  }
  apiUrl = formattedUrl;
}

const envDirectory = path.join(__dirname, '..', 'src', 'environments');
const targetPath = path.join(envDirectory, 'environment.prod.ts');

if (!fs.existsSync(envDirectory)) {
  fs.mkdirSync(envDirectory, { recursive: true });
}

const envConfigFile = `// Auto-generated by scripts/set-env.js at build time
export const environment = {
  production: true,
  apiUrl: '${apiUrl}'
};
`;

fs.writeFileSync(targetPath, envConfigFile, { encoding: 'utf8' });

console.log(`[set-env] Generated environment.prod.ts with apiUrl: "${apiUrl}"`);
